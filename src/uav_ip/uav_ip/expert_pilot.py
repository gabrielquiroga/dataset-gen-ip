#!/usr/bin/env python3
"""
Expert Pilot Node - Parametric waypoint-following for PX4 SITL.

Reads hoop poses and landing position from a YAML file generated by
world_generator.py, auto-computes approach/exit waypoints, and flies
the circuit in Offboard mode.  Exits cleanly (code 0) after landing
so the data_collector orchestrator can detect mission completion.

Usage:
    ros2 run uav_ip expert_pilot --ros-args -p waypoints_file:=/path/to/circuit.yaml
"""

import sys
import math
from pathlib import Path

import yaml
import rclpy
from rclpy.node import Node
from rclpy.qos import (
    QoSProfile,
    ReliabilityPolicy,
    DurabilityPolicy,
    HistoryPolicy,
)

from px4_msgs.msg import (
    OffboardControlMode,
    TrajectorySetpoint,
    VehicleCommand,
    VehicleLocalPosition,
)


class ExpertPilot(Node):
    """State-machine pilot that follows waypoints derived from a YAML circuit file."""

    # --- Tunable constants (metres) ---
    APPROACH_OFFSET: float = 1.0   # distance before/after hoop centre
    TAKEOFF_HEIGHT: float = 1.5    # AGL for initial climb
    HOVER_HEIGHT: float = 1.5      # AGL over landing pad before descent
    TOUCHDOWN_HEIGHT: float = 0.3  # AGL before AUTO_LAND command

    def __init__(self) -> None:
        super().__init__("expert_pilot")

        # -- ROS Parameters -----------------------------------------------
        self.declare_parameter("waypoints_file", "")

        wp_file: str = (
            self.get_parameter("waypoints_file")
            .get_parameter_value()
            .string_value
        )
        if not wp_file:
            self.get_logger().fatal(
                "Parametro 'waypoints_file' no proporcionado.  "
                "Uso: --ros-args -p waypoints_file:=/ruta/al/waypoints.yaml"
            )
            raise SystemExit(1)

        wp_path = Path(wp_file)
        if not wp_path.is_file():
            self.get_logger().fatal(
                f"Archivo de waypoints no encontrado: {wp_file}"
            )
            raise SystemExit(1)

        # -- Build waypoint sequence from YAML ----------------------------
        self.waypoints_gazebo: list[list[float]] = self._build_waypoints(wp_path)
        self.get_logger().info(
            f"Circuito cargado: {len(self.waypoints_gazebo)} waypoints "
            f"desde {wp_path.name}"
        )
        for i, wp in enumerate(self.waypoints_gazebo):
            self.get_logger().info(
                f"  WP {i}: [{wp[0]:.1f}, {wp[1]:.1f}, {wp[2]:.1f}]"
            )

        self.waypoints_ned: list[list[float]] = [
            self._gazebo_to_ned(wp) for wp in self.waypoints_gazebo
        ]

        # -- QoS for PX4 uORB bridge -------------------------------------
        qos = QoSProfile(
            reliability=ReliabilityPolicy.BEST_EFFORT,
            durability=DurabilityPolicy.VOLATILE,
            history=HistoryPolicy.KEEP_LAST,
            depth=1,
        )

        # -- Publishers ---------------------------------------------------
        self.offboard_pub = self.create_publisher(
            OffboardControlMode, "/fmu/in/offboard_control_mode", qos
        )
        self.trajectory_pub = self.create_publisher(
            TrajectorySetpoint, "/fmu/in/trajectory_setpoint", qos
        )
        self.vehicle_cmd_pub = self.create_publisher(
            VehicleCommand, "/fmu/in/vehicle_command", qos
        )

        # -- Subscribers --------------------------------------------------
        self.create_subscription(
            VehicleLocalPosition,
            "/fmu/out/vehicle_local_position_v1",
            self._pos_callback,
            qos,
        )

        # -- Internal state -----------------------------------------------
        self.current_pos_ned: list[float] = [0.0, 0.0, 0.0]
        self.px4_timestamp: int = 0
        self.current_wp: int = 0
        # States: 0=Init  1=Takeoff  2=Navigate  3=LandCmd
        #         4=Landing  5=Done
        self.nav_state: int = 0
        self.setpoint_counter: int = 0
        self.target_yaw: float = math.pi / 2.0

        # -- 50 Hz control timer ------------------------------------------
        self.timer = self.create_timer(0.02, self._control_loop)

    # =================================================================
    #  Waypoint generation from YAML
    # =================================================================
    def _build_waypoints(self, yaml_path: Path) -> list[list[float]]:
        """Parse hoop/landing YAML and produce the full waypoint sequence.

        For each hoop the function creates two waypoints:
          - Pre-alignment:  centre - APPROACH_OFFSET along the hoop forward axis
          - Post-exit:      centre + APPROACH_OFFSET along the hoop forward axis

        The hoop forward axis is determined by its yaw in the SDF world:
          forward = (cos(yaw), sin(yaw), 0)
        """
        with open(yaml_path, "r") as fh:
            cfg = yaml.safe_load(fh)

        wps: list[list[float]] = []

        # WP 0 - Takeoff above origin
        wps.append([0.0, 0.0, self.TAKEOFF_HEIGHT])

        # Per-hoop approach / exit pairs
        for hoop in cfg["hoops"]:
            cx = float(hoop["x"])
            cy = float(hoop["y"])
            cz = float(hoop["z"])
            yaw = float(hoop.get("yaw", 0.0))

            fwd_x = math.cos(yaw)
            fwd_y = math.sin(yaw)

            # Pre-alignment (before the hoop)
            wps.append([
                cx - self.APPROACH_OFFSET * fwd_x,
                cy - self.APPROACH_OFFSET * fwd_y,
                cz,
            ])
            # Post-exit (after the hoop)
            wps.append([
                cx + self.APPROACH_OFFSET * fwd_x,
                cy + self.APPROACH_OFFSET * fwd_y,
                cz,
            ])

        # Landing sequence
        lx = float(cfg["landing"]["x"])
        ly = float(cfg["landing"]["y"])
        wps.append([lx, ly, self.HOVER_HEIGHT])      # Hover above pad
        wps.append([lx, ly, self.TOUCHDOWN_HEIGHT])   # Descend to threshold

        return wps

    # =================================================================
    #  Coordinate helpers
    # =================================================================
    @staticmethod
    def _gazebo_to_ned(coord: list[float]) -> list[float]:
        """Gazebo ENU (X-fwd, Y-left, Z-up) to PX4 NED (N, E, D)."""
        return [coord[1], coord[0], -coord[2]]

    # =================================================================
    #  Callbacks
    # =================================================================
    def _pos_callback(self, msg: VehicleLocalPosition) -> None:
        """Cache latest position and PX4 monotonic timestamp."""
        self.current_pos_ned = [msg.x, msg.y, msg.z]
        self.px4_timestamp = msg.timestamp

    # =================================================================
    #  Main control loop (50 Hz)
    # =================================================================
    def _control_loop(self) -> None:
        # Wait until we receive at least one position message
        if self.px4_timestamp == 0:
            return

        self._publish_offboard_mode()

        # Safety default: hold current position
        target = list(self.current_pos_ned)

        # -- State machine ------------------------------------------------
        if self.nav_state == 0:
            pass  # Streaming idle setpoints, waiting for arming at counter=100

        elif self.nav_state == 1:  # TAKEOFF
            target = self.waypoints_ned[0]
            self.target_yaw = math.pi / 2.0
            if abs(self.current_pos_ned[2] - target[2]) < 0.2:
                self.current_wp = 1
                self.nav_state = 2
                self.get_logger().info(
                    "Despegue completado. Iniciando circuito..."
                )

        elif self.nav_state == 2:  # NAVIGATE (hoops + approach landing)
            target = self.waypoints_ned[self.current_wp]

            dx = target[0] - self.current_pos_ned[0]
            dy = target[1] - self.current_pos_ned[1]
            dz = target[2] - self.current_pos_ned[2]
            dist_xy = math.sqrt(dx * dx + dy * dy)
            dist_3d = math.sqrt(dx * dx + dy * dy + dz * dz)

            # Dynamic yaw: look towards next waypoint
            if dist_xy > 0.5:
                self.target_yaw = math.atan2(dy, dx)

            is_last = self.current_wp == len(self.waypoints_ned) - 1

            if is_last:
                # Stop-and-Drop: tight convergence before land command
                if dist_xy < 0.15 and abs(dz) < 0.15:
                    self.get_logger().info(
                        "Posicion de aterrizaje alcanzada. "
                        "Comandando AUTO_LAND..."
                    )
                    self.nav_state = 3
            else:
                # Fluid hoop crossing: switch at 30 cm sphere
                if dist_3d < 0.3:
                    self.current_wp += 1
                    self.get_logger().info(
                        f"WP {self.current_wp - 1} alcanzado -> "
                        f"rumbo a WP {self.current_wp}"
                    )

        elif self.nav_state == 3:  # LAND COMMAND
            target = self.waypoints_ned[-1]
            self._publish_vehicle_command(
                VehicleCommand.VEHICLE_CMD_NAV_LAND
            )
            self.get_logger().info("VEHICLE_CMD_NAV_LAND enviado.")
            self.nav_state = 4

        elif self.nav_state == 4:  # LANDING IN PROGRESS
            target = self.waypoints_ned[-1]
            # Z in NED is negative-up; near zero means ground contact
            if self.current_pos_ned[2] > -0.05:
                self.get_logger().info(
                    "Contacto con el suelo. Mision completada."
                )
                self.nav_state = 5

        elif self.nav_state == 5:  # DONE - clean exit for orchestrator
            self.get_logger().info("Saliendo con codigo 0 (exito).")
            raise SystemExit(0)

        # -- Publish setpoint (while still actively flying) ----------------
        if self.nav_state < 4:
            self._publish_trajectory_setpoint(
                target[0], target[1], target[2], self.target_yaw
            )

        # -- Arming sequence after 2 s of streaming setpoints --------------
        if self.setpoint_counter == 100:
            self._publish_vehicle_command(
                VehicleCommand.VEHICLE_CMD_DO_SET_MODE, 1.0, 6.0
            )
            self._publish_vehicle_command(
                VehicleCommand.VEHICLE_CMD_COMPONENT_ARM_DISARM, 1.0
            )
            self.nav_state = 1
            self.get_logger().info("Motores armados. Despegue iniciado.")

        if self.setpoint_counter < 101:
            self.setpoint_counter += 1

    # =================================================================
    #  PX4 message helpers
    # =================================================================
    def _publish_offboard_mode(self) -> None:
        msg = OffboardControlMode()
        msg.position = True
        msg.velocity = False
        msg.acceleration = False
        msg.attitude = False
        msg.body_rate = False
        msg.timestamp = self.px4_timestamp
        self.offboard_pub.publish(msg)

    def _publish_trajectory_setpoint(
        self, x: float, y: float, z: float, yaw: float
    ) -> None:
        msg = TrajectorySetpoint()
        msg.position = [float(x), float(y), float(z)]
        msg.velocity = [float("nan")] * 3
        msg.acceleration = [float("nan")] * 3
        msg.jerk = [float("nan")] * 3
        msg.yaw = float(yaw)
        msg.yawspeed = float("nan")
        msg.timestamp = self.px4_timestamp
        self.trajectory_pub.publish(msg)

    def _publish_vehicle_command(
        self,
        command: int,
        param1: float = 0.0,
        param2: float = 0.0,
    ) -> None:
        msg = VehicleCommand()
        msg.command = command
        msg.param1 = float(param1)
        msg.param2 = float(param2)
        msg.target_system = 1
        msg.target_component = 1
        msg.source_system = 1
        msg.source_component = 1
        msg.from_external = True
        msg.timestamp = self.px4_timestamp
        self.vehicle_cmd_pub.publish(msg)


def main(args=None):
    rclpy.init(args=args)
    node = ExpertPilot()
    try:
        rclpy.spin(node)
    except SystemExit as e:
        # Clean exit triggered by mission completion (nav_state == 5)
        node.get_logger().info(f"Nodo terminado con codigo {e.code}.")
    finally:
        if rclpy.ok():
            node.destroy_node()
            rclpy.shutdown()


if __name__ == "__main__":
    main()
